def clean(b):
    return re.sub(r'\s+', ' ', b.replace('　', ' ')).strip()

def main():
    src = sys.argv[1]
    report = sys.argv[sys.argv.index('--report') + 1] if '--report' in sys.argv else None
    d = json.load(open(src, encoding='utf-8'))
    words, chars = {}, collections.defaultdict(collections.Counter)
    for e in d:
        t = e['title']
        if not HAN.fullmatch(t or ''):
            continue
        hs = [clean(h.get('bopomofo', '')) for h in e.get('heteronyms', []) if h.get('bopomofo')]
        if not hs:
            continue
        if len(t) == 1:
            for b in hs:
                chars[t][b] += 0
        else:
            sy = hs[0].split(' ')
            if len(sy) == len(t):
                words.setdefault(t, sy)
                for c, s in zip(t, sy):
                    chars[c][s] += 1
    text = ''.join(open(ROOT / p, encoding='utf-8').read() for p in ('jena-bible/themes.js', 'jena-bible/index.html')) + '\n'.join(SAMPLE)
    runs = HAN.findall(text)
    used = sorted(set(''.join(runs)))
    cdef = {}
    for c in used:
        if c in CHAR_FIX:
            cdef[c] = CHAR_FIX[c]
        elif chars.get(c):
            cdef[c] = chars[c].most_common(1)[0][0]
    fix = {w: r.split(' ') for w, r in WORD_FIX.items() if len(w) == len(r.split(' '))}
    bad = [w for w, r in WORD_FIX.items() if len(w) != len(r.split(' '))]
    if bad:
        sys.exit('WORD_FIX 字數不符：' + '、'.join(bad))
    # 依辭典斷詞，找出和逐字預設不同的詞
    exc = {}
    for run in set(runs):
        i = 0
        while i < len(run):
            for L in range(min(MAXW, len(run) - i), 1, -1):
                w = run[i:i + L]
                if w in fix or w in words:
                    sy = fix.get(w) or words[w]
                    exc[w] = sy
                    i += L
                    break
            else:
                i += 1
    for w, sy in fix.items():
        exc[w] = sy
    out = ROOT / 'jena-bible/zhuyin.js'
    with open(out, 'w', encoding='utf-8') as f:
        f.write('/* 家學堂注音表（自動產生，請改 tools/build-jena-zhuyin.py）\n')
        f.write(' * 讀音來源：教育部《重編國語辭典修訂本》（CC BY-ND 3.0 TW），另經人工校對語境讀音。 */\n')
        f.write('window.JENA_ZY_C=' + json.dumps({c: cdef[c] for c in used if c in cdef}, ensure_ascii=False, separators=(',', ':')) + ';\n')
        f.write('window.JENA_ZY_W=' + json.dumps({w: ' '.join(s) for w, s in sorted(exc.items())}, ensure_ascii=False, separators=(',', ':')) + ';\n')
    missing = [c for c in used if c not in cdef]
    print(f'字 {len(cdef)}，詞 {len(exc)}，沒有讀音的字：{"".join(missing)}')
    if report:
        def annotate(run):
            res, i = [], 0
            while i < len(run):
                for L in range(min(MAXW, len(run) - i), 1, -1):
                    if run[i:i + L] in exc:
                        res += list(zip(run[i:i + L], exc[run[i:i + L]])); i += L; break
                else:
                    res.append((run[i], cdef.get(run[i], '?'))); i += 1
            return res
        poly = {c for c in used if len(chars.get(c, {})) > 1}
        seen = collections.defaultdict(set)
        for run in set(runs):
            a = annotate(run)
            for j, (c, b) in enumerate(a):
                if c in poly:
                    ctx = run[max(0, j - 3):j] + '【' + c + '】' + run[j + 1:j + 4]
                    seen[(c, b)].add(ctx)
        with open(report, 'w', encoding='utf-8') as f:
            for (c, b) in sorted(seen, key=lambda x: (x[0], x[1])):
                ctxs = sorted(seen[(c, b)])
                f.write(f'{c} {b} ({len(ctxs)}): ' + '；'.join(ctxs[:40]) + '\n')

if __name__ == '__main__':
    main()
